CREATE TABLE IF NOT EXISTS module3_templates (
    template_id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(128) NOT NULL DEFAULT 'default',
    filename TEXT NOT NULL,
    path TEXT NOT NULL,
    sheet_name TEXT,
    header_row INTEGER,
    write_row INTEGER,
    table_index INTEGER,
    template_type VARCHAR(32) NOT NULL,
    fields_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    tables_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS module3_docsets (
    doc_set_id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(128) NOT NULL DEFAULT 'default',
    count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS module3_docset_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_set_id VARCHAR(64) NOT NULL REFERENCES module3_docsets(doc_set_id) ON DELETE CASCADE,
    filename TEXT NOT NULL,
    path TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_module3_docset_files_doc_set_id
    ON module3_docset_files (doc_set_id);

CREATE TABLE IF NOT EXISTS module3_runs (
    run_id VARCHAR(64) PRIMARY KEY,
    owner_id VARCHAR(128) NOT NULL DEFAULT 'default',
    status VARCHAR(32) NOT NULL,
    filled INTEGER NOT NULL DEFAULT 0,
    total INTEGER NOT NULL DEFAULT 0,
    fill_rate DOUBLE PRECISION NOT NULL DEFAULT 0,
    output_filename TEXT,
    error TEXT,
    template_id VARCHAR(64) NOT NULL,
    doc_set_id VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS ix_module3_runs_template_id
    ON module3_runs (template_id);

CREATE INDEX IF NOT EXISTS ix_module3_runs_doc_set_id
    ON module3_runs (doc_set_id);

CREATE INDEX IF NOT EXISTS ix_module3_templates_owner_id
    ON module3_templates (owner_id);

CREATE INDEX IF NOT EXISTS ix_module3_docsets_owner_id
    ON module3_docsets (owner_id);

CREATE INDEX IF NOT EXISTS ix_module3_runs_owner_id
    ON module3_runs (owner_id);

