from __future__ import annotations

from dataclasses import dataclass
import time
from typing import Any, Callable, Dict

from ...core.pipeline.document_flow_runtime import (
    DocumentExecutionDependencyBundle,
    DocumentExecutionRuntime,
    DocumentWorkflowRuntime,
)
from ...core.pipeline.document_pipeline_runtime import (
    DocumentPipelineGraphBundle,
    DocumentPipelineInputBundle,
    DocumentPipelineParseBundle,
    DocumentPipelineRuntime,
    DocumentPipelineSchemaBundle,
)
from ...core.pipeline.direct_semantic_extract_runtime import DirectSemanticExtractRuntime
from ...core.pipeline.document_postprocess_runtime import (
    DocumentPostprocessDependencyBundle,
    DocumentPostprocessRuntime,
)


@dataclass(frozen=True)
class Module2MainWorkflowBundle:
    document_execution_runtime: DocumentExecutionRuntime
    document_pipeline_runtime: DocumentPipelineRuntime
    document_postprocess_runtime: DocumentPostprocessRuntime
    document_workflow_runtime: DocumentWorkflowRuntime


def build_module2_main_workflow_bundle(
    *,
    build_stream_router,
    cached_extraction_restore_runtime,
    normalize_soft_warnings,
    promote_visual_diagnostics,
    persist_assistant_payload_artifact,
    persist_field_results_artifact,
    extraction_result_factory,
    document_response_factory,
    save_extraction_result,
    document_input_plan_runtime,
    word_input_preparation_runtime,
    parse_preparation_runtime,
    document_parse_recovery_runtime,
    schema_session_runtime,
    extraction_graph_runtime,
    preflight_nonpdf_profile,
    resolve_nonpdf_budgets,
    resolve_nonpdf_plan,
    apply_field_extract_timeout_floor,
    word_pdf_required,
    is_word_file,
    office_convert_enabled,
    docx_native_recovery_enabled,
    validate_word_preconditions,
    resolve_conversion_timeout,
    build_word_pdf_success,
    resolve_word_pdf_failure,
    build_doc_to_docx_success,
    build_doc_to_docx_failure,
    word_pdf_semaphore,
    ensure_preview_job_started,
    await_or_reuse_pdf,
    run_with_progress_heartbeat,
    convert_doc_to_docx_with_timeout,
    tighten_parse_budgets_before_parse,
    build_parse_session,
    build_parse_attempt_runner,
    acquire_parse_execution_slots,
    run_parse_in_process_pool,
    resolve_parse_progress_ramp_sec,
    unpack_parse_output,
    visual_parse_policy_runtime,
    parse_fallback_coordinator_runtime,
    docx_native_recovery_runtime,
    fasttrack_fallback_runtime,
    visual_chain_required,
    visual_strict_mode,
    disable_fasttrack_fallback,
    build_visual_chain_contract,
    extraction_llm_semaphore,
    graph,
    detect_domain_template,
    extract_text_for_schema,
    resolve_effective_schema,
    resolve_dynamic_extract_timeout_sec,
    schema_target_fields,
    normalize_schema_fields,
    schema_auto_infer_requested,
    sanitize_field_name,
    coerce_field_type,
    upsert_schema_field_candidate,
    filter_auto_schema_fields,
    run_graph,
    resolve_extract_progress_ramp_sec,
    quick_extract_from_tables,
    disable_quick_table_fallback,
    xlsx_workbook_artifact_runtime,
    logger,
    post_parse_quality_runtime,
    post_parse_artifact_runtime,
    diagnostics_builder_runtime,
    extraction_response_runtime,
    graph_diagnostics_factory,
    current_extraction_logic_version,
    current_extraction_logic_components,
    field_naming_version: str,
    schema_rule_versions: Dict[str, Any],
    is_low_value_auto_schema_field_name,
    has_meaningful_value,
    is_low_value_quick_fallback_value,
    is_recoverable_timeout_error,
    filter_low_value_auto_results,
    effective_quality_schema_fields,
    result_quality_snapshot,
    strip_recovered_extract_warnings,
    write_artifact_bytes,
    crop_pdf_region_png,
    build_document_trace_hits,
    trace_stats_builder,
    build_polymorphic_links,
    count_table_cells,
    table_quality_avg,
    table_source_counts,
    count_figure_dataframe_cells,
    figure_pages,
    figure_source_counts,
    persist_assistant1_source_markdown_artifact,
    perf_counter: Callable[[], float] | None = None,
) -> Module2MainWorkflowBundle:
    document_execution_bundle = DocumentExecutionDependencyBundle(
        build_stream_router=build_stream_router,
        cached_extraction_restore_runtime=cached_extraction_restore_runtime,
        normalize_soft_warnings=normalize_soft_warnings,
        promote_visual_diagnostics=promote_visual_diagnostics,
        persist_assistant_payload_artifact=persist_assistant_payload_artifact,
        persist_field_results_artifact=persist_field_results_artifact,
        extraction_result_factory=extraction_result_factory,
        document_response_factory=document_response_factory,
        save_extraction_result=save_extraction_result,
    )
    document_execution_runtime = DocumentExecutionRuntime(
        dependency_bundle=document_execution_bundle,
    )

    document_pipeline_input_bundle = DocumentPipelineInputBundle(
        document_input_plan_runtime=document_input_plan_runtime,
        word_input_preparation_runtime=word_input_preparation_runtime,
        preflight_nonpdf_profile=preflight_nonpdf_profile,
        resolve_nonpdf_budgets=resolve_nonpdf_budgets,
        resolve_nonpdf_plan=resolve_nonpdf_plan,
        apply_field_extract_timeout_floor=apply_field_extract_timeout_floor,
        word_pdf_required=word_pdf_required,
        is_word_file=is_word_file,
        office_convert_enabled=office_convert_enabled,
        docx_native_recovery_enabled=docx_native_recovery_enabled,
        validate_word_preconditions=validate_word_preconditions,
        resolve_conversion_timeout=resolve_conversion_timeout,
        build_word_pdf_success=build_word_pdf_success,
        resolve_word_pdf_failure=resolve_word_pdf_failure,
        build_doc_to_docx_success=build_doc_to_docx_success,
        build_doc_to_docx_failure=build_doc_to_docx_failure,
        word_pdf_semaphore=word_pdf_semaphore,
        ensure_preview_job_started=ensure_preview_job_started,
        await_or_reuse_pdf=await_or_reuse_pdf,
        run_with_progress_heartbeat=run_with_progress_heartbeat,
        convert_doc_to_docx_with_timeout=convert_doc_to_docx_with_timeout,
    )
    document_pipeline_parse_bundle = DocumentPipelineParseBundle(
        parse_preparation_runtime=parse_preparation_runtime,
        document_parse_recovery_runtime=document_parse_recovery_runtime,
        tighten_parse_budgets_before_parse=tighten_parse_budgets_before_parse,
        build_parse_session=build_parse_session,
        build_parse_attempt_runner=build_parse_attempt_runner,
        acquire_parse_execution_slots=acquire_parse_execution_slots,
        run_parse_in_process_pool=run_parse_in_process_pool,
        run_with_progress_heartbeat=run_with_progress_heartbeat,
        resolve_parse_progress_ramp_sec=resolve_parse_progress_ramp_sec,
        unpack_parse_output=unpack_parse_output,
        visual_parse_policy_runtime=visual_parse_policy_runtime,
        parse_fallback_coordinator_runtime=parse_fallback_coordinator_runtime,
        docx_native_recovery_runtime=docx_native_recovery_runtime,
        fasttrack_fallback_runtime=fasttrack_fallback_runtime,
        is_word_file=is_word_file,
        visual_chain_required=visual_chain_required,
        docx_native_recovery_enabled=docx_native_recovery_enabled,
        visual_strict_mode=visual_strict_mode,
        disable_fasttrack_fallback=disable_fasttrack_fallback,
    )
    document_pipeline_schema_bundle = DocumentPipelineSchemaBundle(
        schema_session_runtime=schema_session_runtime,
        extraction_llm_semaphore=extraction_llm_semaphore,
        detect_domain_template=detect_domain_template,
        extract_text_for_schema=extract_text_for_schema,
        resolve_effective_schema=resolve_effective_schema,
        resolve_dynamic_extract_timeout_sec=resolve_dynamic_extract_timeout_sec,
        is_word_file=is_word_file,
    )
    document_pipeline_graph_bundle = DocumentPipelineGraphBundle(
        extraction_graph_runtime=extraction_graph_runtime,
        run_graph=run_graph,
        extraction_llm_semaphore=extraction_llm_semaphore,
        run_with_progress_heartbeat=run_with_progress_heartbeat,
        resolve_extract_progress_ramp_sec=resolve_extract_progress_ramp_sec,
        quick_extract_from_tables=quick_extract_from_tables,
        disable_quick_table_fallback=disable_quick_table_fallback,
    )
    direct_semantic_extract_runtime = DirectSemanticExtractRuntime(
        graph=graph,
        extraction_llm_semaphore=extraction_llm_semaphore,
        schema_target_fields=schema_target_fields,
        normalize_schema_fields=normalize_schema_fields,
        schema_auto_infer_requested=schema_auto_infer_requested,
        sanitize_field_name=sanitize_field_name,
        coerce_field_type=coerce_field_type,
        upsert_schema_field_candidate=upsert_schema_field_candidate,
        filter_auto_schema_fields=filter_auto_schema_fields,
        detect_domain_template=detect_domain_template,
        extract_text_for_schema=extract_text_for_schema,
    )

    document_pipeline_runtime = DocumentPipelineRuntime(
        input_bundle=document_pipeline_input_bundle,
        parse_bundle=document_pipeline_parse_bundle,
        schema_bundle=document_pipeline_schema_bundle,
        graph_bundle=document_pipeline_graph_bundle,
        direct_semantic_extract_runtime=direct_semantic_extract_runtime,
        build_visual_chain_contract=build_visual_chain_contract,
        xlsx_workbook_artifact_runtime=xlsx_workbook_artifact_runtime,
        logger=logger,
        perf_counter=perf_counter if perf_counter is not None else time.perf_counter,
    )

    document_postprocess_bundle = DocumentPostprocessDependencyBundle(
        post_parse_quality_runtime=post_parse_quality_runtime,
        post_parse_artifact_runtime=post_parse_artifact_runtime,
        diagnostics_builder_runtime=diagnostics_builder_runtime,
        extraction_response_runtime=extraction_response_runtime,
        graph_diagnostics_factory=graph_diagnostics_factory,
        is_word_file=is_word_file,
        current_extraction_logic_version=current_extraction_logic_version,
        current_extraction_logic_components=current_extraction_logic_components,
        field_naming_version=field_naming_version,
        schema_rule_versions=schema_rule_versions,
        normalize_soft_warnings=normalize_soft_warnings,
        is_low_value_auto_schema_field_name=is_low_value_auto_schema_field_name,
        has_meaningful_value=has_meaningful_value,
        is_low_value_quick_fallback_value=is_low_value_quick_fallback_value,
        is_recoverable_timeout_error=is_recoverable_timeout_error,
        filter_low_value_auto_results=filter_low_value_auto_results,
        effective_quality_schema_fields=effective_quality_schema_fields,
        result_quality_snapshot=result_quality_snapshot,
        strip_recovered_extract_warnings=strip_recovered_extract_warnings,
        write_artifact_bytes=write_artifact_bytes,
        crop_pdf_region_png=crop_pdf_region_png,
        build_document_trace_hits=build_document_trace_hits,
        trace_stats_builder=trace_stats_builder,
        build_polymorphic_links=build_polymorphic_links,
        count_table_cells=count_table_cells,
        table_quality_avg=table_quality_avg,
        table_source_counts=table_source_counts,
        count_figure_dataframe_cells=count_figure_dataframe_cells,
        figure_pages=figure_pages,
        figure_source_counts=figure_source_counts,
        persist_assistant1_source_markdown_artifact=persist_assistant1_source_markdown_artifact,
        persist_assistant_payload_artifact=persist_assistant_payload_artifact,
        persist_field_results_artifact=persist_field_results_artifact,
        promote_visual_diagnostics=promote_visual_diagnostics,
        extraction_result_factory=extraction_result_factory,
        document_response_factory=document_response_factory,
    )
    document_postprocess_runtime = DocumentPostprocessRuntime(
        dependency_bundle=document_postprocess_bundle,
    )

    document_workflow_runtime = DocumentWorkflowRuntime(
        document_execution_runtime=document_execution_runtime,
        document_pipeline_runtime=document_pipeline_runtime,
        document_postprocess_runtime=document_postprocess_runtime,
        perf_counter=perf_counter if perf_counter is not None else time.perf_counter,
    )

    return Module2MainWorkflowBundle(
        document_execution_runtime=document_execution_runtime,
        document_pipeline_runtime=document_pipeline_runtime,
        document_postprocess_runtime=document_postprocess_runtime,
        document_workflow_runtime=document_workflow_runtime,
    )
